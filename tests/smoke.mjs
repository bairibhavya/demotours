import assert from 'node:assert/strict';
import {INITIAL_PACKAGES,DESTINATIONS} from '../src/data.js';
import {prefixMatch,rupees,slugify} from '../src/lib/format.js';
const matched=DESTINATIONS.filter(d=>prefixMatch(d.name,'k')).map(x=>x.name).sort();
assert.deepEqual(matched,['Kashmir','Kerala'],'typing one lowercase k should immediately match Kerala and Kashmir');
assert(prefixMatch('Kerala','K'),'search should ignore case');
assert(prefixMatch('Himachal Escape','escape'),'word prefix search should work');
assert(!prefixMatch('Goa','k'),'typing k must not display unrelated Goa');
const under17000=INITIAL_PACKAGES.filter(p=>p.price>=0&&p.price<=17000);
assert(under17000.some(p=>p.destination==='Kerala'));
assert(under17000.some(p=>p.destination==='Goa'));
assert(!under17000.some(p=>p.destination==='Andaman'));
assert(INITIAL_PACKAGES.every(p=>Number(p.price)>0&&p.slug&&p.image&&Array.isArray(p.itinerary)));
assert.equal(new Set(INITIAL_PACKAGES.map(p=>p.slug)).size,INITIAL_PACKAGES.length);
assert.equal(slugify('Kerala Backwaters'),'kerala-backwaters');
assert.equal(rupees(16999),'₹16,999');
console.log('PASS: case-insensitive instant destination prefix search (k ⇒ Kerala, Kashmir)');
console.log('PASS: package price range filtering at ₹17,000');
console.log('PASS: sample package completeness, unique slugs, Indian price formatting');
